#!/usr/bin/env node
/**
 * Build the Institution Credential ID assignment.
 *
 *     node scripts/build-credential-ids.mjs [--write]
 *
 * WHAT THIS IS FOR. The ICID column arrives with a database default, because a
 * NOT NULL column cannot be added to a populated table without one. That
 * default is `gen_random_uuid()`, so the thirteen certificates of 8 August —
 * which were imported before the column existed — would each get whatever
 * value the database happened to generate at ALTER TABLE time. Different in
 * every environment, different again after any rebuild, and therefore useless
 * as the permanent identifier an audit log is allowed to reference.
 *
 * This file pins them instead: every certificate's ICID is the UUIDv5 that
 * functions/_lib/credential-id.js derives from its own stored serial, so the
 * value is a property of the certificate rather than of the database that
 * happened to hold it first.
 *
 * It covers ALL certificates on the published registers, not only the
 * thirteen. For the thirty-three minted on 15 August the UPDATE is a no-op —
 * their INSERT already carries the same derived value — and that is the point:
 * running this file proves the two paths agree rather than assuming it.
 *
 * It recomputes no hash, no serial and no printed identifier. It reads the
 * sealed registers and writes one column.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { credentialIdFor } from '../functions/_lib/credential-id.js';

const DIR = 'docs/graduation-registers';
const OUT = `${DIR}/2026-08-15-CREDENTIAL-IDS.sql`;

const rows = [];
for (const f of readdirSync(DIR).filter((x) => x.endsWith('.json') && /^\d{4}-/.test(x)).sort()) {
  const reg = JSON.parse(readFileSync(join(DIR, f), 'utf8'));
  for (const e of reg.entries || []) {
    const icid = credentialIdFor(e.serialNo);
    // Where the register already carries one — the batches minted on
    // 15 August — it must agree. A disagreement means the derivation changed
    // under a sealed register, which is the one thing that must never happen
    // silently.
    if (e.credentialId && e.credentialId !== icid) {
      console.error(`  ${e.serialNo}: register says ${e.credentialId}, derivation says ${icid}.`);
      console.error('  Refusing to write. The ICID derivation has changed under a sealed register.');
      process.exit(2);
    }
    rows.push({ serial: e.serialNo, icid, name: e.studentEn, sealed: Boolean(e.credentialId) });
  }
}
if (!rows.length) { console.error(`  No published registers in ${DIR}.`); process.exit(2); }

const dupes = rows.filter((r, i) => rows.findIndex((x) => x.icid === r.icid) !== i);
if (dupes.length) {
  console.error(`  ${dupes.length} ICID collision(s). Refusing to write.`);
  process.exit(2);
}

const sq = (s) => `'${String(s).replace(/'/g, "''")}'`;
const sealed = rows.filter((r) => r.sealed).length;

const out = `-- SHRS — INSTITUTION CREDENTIAL ID ASSIGNMENT
-- Generated by scripts/build-credential-ids.mjs from the published registers.
--
-- ${rows.length} certificates. ${sealed} carry this value in their own sealed register
-- already (minted 15 Aug 2026, ICID written at issuance); for those the UPDATE
-- below changes nothing and exists to PROVE the issuance path and the
-- derivation agree. The remaining ${rows.length - sealed} predate the column and are pinned here.
--
-- The ICID is UUIDv5(stored serial, SHRS namespace) — see
-- functions/_lib/credential-id.js for why it is derived rather than random.
-- It is never printed on a certificate and never returned to the public.
--
-- SAFE TO RUN REPEATEDLY. Every value is a pure function of a serial that is
-- engraved on paper and cannot change, so a second run writes the same values.
--
-- ONE TRANSACTION, with an assertion at the end.

BEGIN;

${rows.map((r) => `UPDATE stage_certificates SET credential_id = ${sq(r.icid)}::uuid\n  WHERE serial_no = ${sq(r.serial)};  -- ${r.name}`).join('\n')}

-- ─────────────────────────────────────────────────────────────────────────
-- THE ASSERTION. Two ways this could go wrong quietly, both checked:
--
--   1. A certificate on file carries an ICID that is NOT in the list above —
--      meaning it is still holding the database-generated default, and the
--      permanent identifier is an accident of which environment inserted it.
--   2. Two certificates share one. UNIQUE would already have refused the
--      write, but reporting it here names the pair instead of raising 23505.
-- ─────────────────────────────────────────────────────────────────────────
DO $$
DECLARE
  stray text;
  n    int;
BEGIN
  SELECT string_agg(serial_no, E'\\n    '), count(*) INTO stray, n
  FROM stage_certificates
  WHERE credential_id NOT IN (
${rows.map((r) => `    ${sq(r.icid)}::uuid`).join(',\n')}
  );
  IF n > 0 THEN
    RAISE EXCEPTION E'ABORTED — % certificate(s) still carry a database-generated ICID rather than their derived one:\\n    %', n, stray;
  END IF;
END $$;

SELECT 'credential ids assigned' AS check, count(*)::text AS value FROM stage_certificates
UNION ALL SELECT 'distinct credential ids', count(DISTINCT credential_id)::text FROM stage_certificates;

COMMIT;
`;

if (process.argv.includes('--write')) {
  writeFileSync(OUT, out);
  console.log(`\n  Wrote ${OUT}`);
} else {
  console.log('\n  (dry run — pass --write to produce the file)');
}
console.log(`    ${rows.length} certificates · ${sealed} already sealed with this ICID · `
  + `${rows.length - sealed} pinned here · 0 collisions\n`);
for (const r of rows.slice(0, 3)) console.log(`    ${r.serial}  ${r.icid}`);
console.log(`    … and ${rows.length - 3} more\n`);
