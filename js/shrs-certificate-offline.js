/* Sultan Hanafi Royal Schools — offline certificate checking.
 *
 * THE CONSTRAINT THAT SHAPES ALL OF THIS
 *
 * A certificate's integrity is proved by an HMAC-SHA256 over its fields, keyed
 * by DOCUMENT_HASH_SECRET. HMAC is symmetric: the key that verifies is the key
 * that signs. Putting it on a device to enable offline verification would hand
 * every holder the power to mint a certificate that verifies. That is not a
 * trade-off to be weighed; it is the end of the verification system.
 *
 * So offline checking does NOT verify integrity, and this module never says a
 * certificate is genuine. It answers a strictly weaker question — "is this
 * serial recorded as issued, and what is its status?" — from a REGISTER the
 * school signs with an asymmetric key. The private half never leaves the
 * server. The public half proves the register is the school's.
 *
 *   ONLINE   full verification: the serial resolves AND its content hash
 *            matches → "Genuine".
 *   OFFLINE  register lookup only → "Recorded as issued" or "Revoked", each
 *            stamped with when the register was signed.
 *
 * No state this module can return is ever "Genuine". That is not an oversight
 * to be corrected later; it is the guarantee.
 *
 * Serials are stored in the register as SHA-256 digests, not in the clear. The
 * register has to be a public file for an offline device to hold it, and a
 * public file listing every serial the school has ever issued is an
 * enumeration list. A holder can still check the serial they are looking at,
 * because they have it to hash.
 */
import { LIFETIMES } from './shrs-offline-policy.js';

export const STATE = {
  RECORDED: 'recorded',                 // in the register, status valid
  REVOKED: 'revoked',                   // in the register, withdrawn
  NOT_IN_REGISTER: 'not-in-register',   // no entry — NOT "forged"
  REGISTER_STALE: 'register-stale',     // older than the revocation window
  REGISTER_UNTRUSTED: 'register-untrusted', // signature absent, wrong, or unpinned key
  REGISTER_ABSENT: 'register-absent',   // nothing on this device to check against
};

/*
 * The pinned public keys.
 *
 * DELIBERATELY EMPTY. The production key pair does not exist yet: it must be
 * generated by the Founder, its private half held as a deployment secret, and
 * only its public half added here. Until that happens every register is
 * REGISTER_UNTRUSTED and every offline check refuses — which is the correct
 * behaviour, not a gap. A placeholder key here would be worse than none: it
 * would make an unsigned register look checked.
 *
 * Format: keyId -> base64 SPKI of an Ed25519 public key.
 */
export const TRUSTED_KEYS = Object.freeze({});

const REGISTER_URL = '/verify-certificate/register.json';
const CACHE_NAME = 'shrs-certificate-register';

/* ── Serial handling ─────────────────────────────────────────────────────── */

// Matches the normalisation the online verifier performs, so a serial typed
// with different spacing or case resolves to the same digest.
export function normaliseSerial(input) {
  return String(input || '').toUpperCase().replace(/\s+/g, '').trim();
}

export async function serialDigest(serial) {
  const bytes = new TextEncoder().encode(normaliseSerial(serial));
  const hash = await crypto.subtle.digest('SHA-256', bytes);
  return [...new Uint8Array(hash)].map((b) => b.toString(16).padStart(2, '0')).join('').slice(0, 32);
}

/* ── Signature ───────────────────────────────────────────────────────────── */

// The signed bytes are the register with its signature removed, serialised
// with keys sorted at EVERY level. Both halves must agree exactly on this or
// every signature fails; it is written once here and once in
// scripts/build-certificate-register.mjs.
//
// Written by hand rather than with JSON.stringify(value, keyArray), which was
// the first attempt and was badly wrong: an array replacer is an allowlist
// applied RECURSIVELY, so the top-level key names filtered out h, s and d from
// every entry and each one serialised as {}. The signature therefore covered
// the register's shape and almost none of its content — a revocation could
// have been flipped back to valid on a device and still verified. The
// acceptance run caught it; nothing signed by this code ever shipped.
function canonicalise(value) {
  if (Array.isArray(value)) return '[' + value.map(canonicalise).join(',') + ']';
  if (value && typeof value === 'object') {
    return '{' + Object.keys(value).sort()
      .map((k) => JSON.stringify(k) + ':' + canonicalise(value[k]))
      .join(',') + '}';
  }
  return JSON.stringify(value === undefined ? null : value);
}

export function canonicalBytes(register) {
  const { signature, ...rest } = register;
  return new TextEncoder().encode(canonicalise(rest));
}

function fromBase64(b64) {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i += 1) out[i] = bin.charCodeAt(i);
  return out;
}

export async function verifyRegister(register, trustedKeys = TRUSTED_KEYS) {
  if (!register || !register.signature || !register.keyId) return { trusted: false, reason: 'unsigned' };
  const pinned = trustedKeys[register.keyId];
  if (!pinned) return { trusted: false, reason: 'key-not-pinned', keyId: register.keyId };
  if (register.algorithm !== 'Ed25519') return { trusted: false, reason: 'algorithm-not-accepted' };

  let key;
  try {
    key = await crypto.subtle.importKey('spki', fromBase64(pinned), { name: 'Ed25519' }, false, ['verify']);
  } catch (e) {
    return { trusted: false, reason: 'key-unusable' };
  }

  let ok = false;
  try {
    ok = await crypto.subtle.verify('Ed25519', key, fromBase64(register.signature), canonicalBytes(register));
  } catch (e) {
    ok = false;
  }
  return ok ? { trusted: true } : { trusted: false, reason: 'signature-invalid' };
}

/* ── Holding the register ────────────────────────────────────────────────── */

export async function fetchRegister(url = REGISTER_URL) {
  const res = await fetch(url, { credentials: 'omit' });
  if (!res.ok) throw new Error('register HTTP ' + res.status);
  const register = await res.json();
  try {
    const cache = await caches.open(CACHE_NAME);
    await cache.put(url, new Response(JSON.stringify(register), { headers: { 'content-type': 'application/json' } }));
  } catch (e) { /* no CacheStorage — the register simply is not held */ }
  return register;
}

export async function heldRegister(url = REGISTER_URL) {
  try {
    const cache = await caches.open(CACHE_NAME);
    const res = await cache.match(url);
    if (!res) return null;
    return await res.json();
  } catch (e) {
    return null;
  }
}

/* ── The check ───────────────────────────────────────────────────────────── */

/**
 * Checks one serial against a register. Every refusal is a distinct state with
 * its own sentence — "not in this register" is not "forged", and a stale
 * register is not a verdict on the certificate at all.
 */
export async function check(serial, options = {}) {
  const register = options.register || await heldRegister(options.url);
  if (!register) return { state: STATE.REGISTER_ABSENT, genuine: false };

  const verdict = await verifyRegister(register, options.trustedKeys);
  if (!verdict.trusted) {
    return { state: STATE.REGISTER_UNTRUSTED, genuine: false, reason: verdict.reason, keyId: register.keyId };
  }

  // The revocation window IS the freshness window. A register signed before a
  // certificate was withdrawn would still say "recorded", so past this age it
  // refuses to answer rather than answering out of date.
  const age = Date.now() - (register.issuedAt || 0);
  if (age > LIFETIMES.certificateManifestMaxAgeMs) {
    return { state: STATE.REGISTER_STALE, genuine: false, signedAt: register.issuedAt, ageMs: age };
  }

  const digest = await serialDigest(serial);
  const entry = (register.entries || []).find((e) => e.h === digest);
  if (!entry) {
    return { state: STATE.NOT_IN_REGISTER, genuine: false, signedAt: register.issuedAt };
  }
  return {
    state: entry.s === 'revoked' ? STATE.REVOKED : STATE.RECORDED,
    genuine: false,                 // never, from this module, under any path
    issuedOn: entry.d || null,
    signedAt: register.issuedAt,
  };
}

