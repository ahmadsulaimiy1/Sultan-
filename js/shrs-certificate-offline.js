export function describe(result, lang = 'en') {
  const t = WORDS[lang] || WORDS.en;
  const when = result.signedAt ? new Date(result.signedAt).toISOString().slice(0, 16).replace('T', ' ') : '';
  const fill = (s) => String(s).replace('{when}', when);
  switch (result.state) {
    case STATE.RECORDED: return { tone: 'partial', title: t.recorded, note: fill(t.recordedNote) };
    case STATE.REVOKED: return { tone: 'revoked', title: t.revoked, note: fill(t.revokedNote) };
    case STATE.NOT_IN_REGISTER: return { tone: 'unknown', title: t.notInRegister, note: t.notInRegisterNote };
    case STATE.REGISTER_STALE: return { tone: 'unknown', title: t.stale, note: t.staleNote };
    case STATE.REGISTER_UNTRUSTED: return { tone: 'unknown', title: t.untrusted, note: t.untrustedNote };
    default: return { tone: 'unknown', title: t.absent, note: t.absentNote };
  }
}
